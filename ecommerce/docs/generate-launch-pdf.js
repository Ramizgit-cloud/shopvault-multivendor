const pageWidth = 595.28;
const pageHeight = 841.89;
const margin = 54;
const maxWidth = pageWidth - margin * 2;
const pages = [];
let current = [];
let y = pageHeight - margin;

function escapePdf(value) {
  return String(value).replace(/\\/g, '\\\\').replace(/\(/g, '\\(').replace(/\)/g, '\\)');
}

function wrapText(text, fontSize, prefixWidth = 0) {
  const avgCharWidth = fontSize * 0.52;
  const maxChars = Math.max(18, Math.floor((maxWidth - prefixWidth) / avgCharWidth));
  const lines = [];
  for (const rawLine of String(text).split('\n')) {
    const words = rawLine.trim().split(/\s+/).filter(Boolean);
    if (!words.length) {
      lines.push('');
      continue;
    }
    let line = '';
    for (const word of words) {
      const candidate = line ? `${line} ${word}` : word;
      if (candidate.length > maxChars && line) {
        lines.push(line);
        line = word;
      } else {
        line = candidate;
      }
    }
    lines.push(line);
  }
  return lines;
}

function newPage() {
  if (current.length) pages.push(current);
  current = [];
  y = pageHeight - margin;
}

function ensureSpace(height) {
  if (y - height < margin) newPage();
}

function drawText(text, x, font, size, lineHeight) {
  ensureSpace(lineHeight);
  current.push(`BT /${font} ${size} Tf ${x.toFixed(2)} ${y.toFixed(2)} Td (${escapePdf(text)}) Tj ET`);
  y -= lineHeight;
}

function addWrapped(text, options = {}) {
  const font = options.font || 'F1';
  const size = options.size || 11;
  const lineHeight = options.lineHeight || size * 1.35;
  const x = options.x || margin;
  const prefix = options.prefix || '';
  const lines = wrapText(text, size, options.prefixWidth || 0);
  lines.forEach((line, index) => {
    drawText(index === 0 ? `${prefix}${line}` : line, index === 0 ? x : x + (options.hang || 0), font, size, lineHeight);
  });
}

for (const block of blocks) {
  if (block.type === 'title') {
    addWrapped(block.text, { font: 'F2', size: 24, lineHeight: 32 });
    y -= 6;
  } else if (block.type === 'subtitle') {
    addWrapped(block.text, { size: 12, lineHeight: 18 });
    y -= 14;
  } else if (block.type === 'note') {
    y -= 4;
    addWrapped(block.text, { font: 'F2', size: 10.5, lineHeight: 15 });
    y -= 10;
  } else if (block.type === 'heading') {
    y -= 10;
    addWrapped(block.text, { font: 'F2', size: 15, lineHeight: 22 });
    y -= 2;
  } else if (block.type === 'paragraph') {
    addWrapped(block.text, { size: 11, lineHeight: 15 });
    y -= 4;
  } else if (block.type === 'mono') {
    y -= 4;
    for (const line of block.text.split('\n')) {
      addWrapped(line || ' ', { font: 'F3', size: 8.8, lineHeight: 12 });
    }
    y -= 6;
  } else if (block.type === 'list') {
    block.items.forEach((item, index) => {
      addWrapped(item, {
        size: 10.5,
        lineHeight: 15,
        x: margin,
        prefix: `${index + 1}. `,
        prefixWidth: 22,
        hang: 18,
      });
    });
    y -= 4;
  }
}
if (current.length) pages.push(current);

const objects = [];
function addObject(body) {
  objects.push(body);
  return objects.length;
}

const catalogId = addObject('');
const pagesId = addObject('');
const fontRegularId = addObject('<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>');
const fontBoldId = addObject('<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>');
const fontMonoId = addObject('<< /Type /Font /Subtype /Type1 /BaseFont /Courier >>');
const pageIds = [];

pages.forEach((commands) => {
  const stream = commands.join('\n');
  const contentId = addObject(`<< /Length ${Buffer.byteLength(stream, 'latin1')} >>\nstream\n${stream}\nendstream`);
  const pageId = addObject(`<< /Type /Page /Parent ${pagesId} 0 R /MediaBox [0 0 ${pageWidth} ${pageHeight}] /Resources << /Font << /F1 ${fontRegularId} 0 R /F2 ${fontBoldId} 0 R /F3 ${fontMonoId} 0 R >> >> /Contents ${contentId} 0 R >>`);
  pageIds.push(pageId);
});

objects[catalogId - 1] = `<< /Type /Catalog /Pages ${pagesId} 0 R >>`;
objects[pagesId - 1] = `<< /Type /Pages /Kids [${pageIds.map((id) => `${id} 0 R`).join(' ')}] /Count ${pageIds.length} >>`;

let pdf = '%PDF-1.4\n%\xE2\xE3\xCF\xD3\n';
const offsets = [0];
objects.forEach((body, index) => {
  offsets.push(Buffer.byteLength(pdf, 'latin1'));
  pdf += `${index + 1} 0 obj\n${body}\nendobj\n`;
});

const xrefOffset = Buffer.byteLength(pdf, 'latin1');
pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
for (let i = 1; i < offsets.length; i += 1) {
  pdf += `${String(offsets[i]).padStart(10, '0')} 00000 n \n`;
}
pdf += `trailer\n<< /Size ${objects.length + 1} /Root ${catalogId} 0 R >>\nstartxref\n${xrefOffset}\n%%EOF\n`;

fs.writeFileSync(outputPath, Buffer.from(pdf, 'latin1'));
console.log(`Generated ${outputPath}`);
