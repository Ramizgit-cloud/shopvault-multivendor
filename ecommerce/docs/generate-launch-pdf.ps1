$PageWidth = 595.28
$PageHeight = 841.89
$Margin = 54
$MaxWidth = $PageWidth - ($Margin * 2)
$Pages = New-Object System.Collections.ArrayList
$Current = New-Object System.Collections.ArrayList
$Y = $PageHeight - $Margin

function Escape-PdfText([string]$Value) {
  return $Value.Replace("\", "\\").Replace("(", "\(").Replace(")", "\)")
}

function Wrap-Text([string]$Text, [double]$FontSize, [double]$PrefixWidth = 0) {
  $avgCharWidth = $FontSize * 0.52
  $maxChars = [Math]::Max(18, [Math]::Floor(($script:MaxWidth - $PrefixWidth) / $avgCharWidth))
  $lines = New-Object System.Collections.ArrayList
  foreach ($rawLine in $Text -split "`n") {
    $words = @($rawLine.Trim() -split "\s+" | Where-Object { $_ })
    if ($words.Count -eq 0) {
      [void]$lines.Add("")
      continue
    }
    $line = ""
    foreach ($word in $words) {
      $candidate = if ($line) { "$line $word" } else { $word }
      if ($candidate.Length -gt $maxChars -and $line) {
        [void]$lines.Add($line)
        $line = $word
      } else {
        $line = $candidate
      }
    }
    [void]$lines.Add($line)
  }
  return $lines
}

function New-PdfPage {
  if ($script:Current.Count -gt 0) {
    [void]$script:Pages.Add($script:Current)
  }
  $script:Current = New-Object System.Collections.ArrayList
  $script:Y = $script:PageHeight - $script:Margin
}

function Ensure-Space([double]$Height) {
  if (($script:Y - $Height) -lt $script:Margin) {
    New-PdfPage
  }
}

function Draw-Text([string]$Text, [double]$X, [string]$Font, [double]$Size, [double]$LineHeight) {
  Ensure-Space $LineHeight
  $safe = Escape-PdfText $Text
  [void]$script:Current.Add(("BT /{0} {1} Tf {2:N2} {3:N2} Td ({4}) Tj ET" -f $Font, $Size, $X, $script:Y, $safe))
  $script:Y -= $LineHeight
}

function Add-Wrapped([string]$Text, [string]$Font = "F1", [double]$Size = 11, [double]$LineHeight = 15, [double]$X = $script:Margin, [string]$Prefix = "", [double]$PrefixWidth = 0, [double]$Hang = 0) {
  $lines = Wrap-Text $Text $Size $PrefixWidth
  for ($i = 0; $i -lt $lines.Count; $i++) {
    $lineText = if ($i -eq 0) { "$Prefix$($lines[$i])" } else { $lines[$i] }
    $lineX = if ($i -eq 0) { $X } else { $X + $Hang }
    Draw-Text $lineText $lineX $Font $Size $LineHeight
  }
}

