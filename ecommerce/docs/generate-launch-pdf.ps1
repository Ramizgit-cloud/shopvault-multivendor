      $Y -= 10
    }
    "heading" {
      $Y -= 10
      Add-Wrapped $block.Text "F2" 15 22
      $Y -= 2
    }
    "paragraph" {
      Add-Wrapped $block.Text "F1" 11 15
      $Y -= 4
    }
    "mono" {
      $Y -= 4
      foreach ($line in $block.Text -split "`n") {
        Add-Wrapped $(if ($line) { $line } else { " " }) "F3" 8.8 12
      }
      $Y -= 6
    }
    "list" {
      for ($i = 0; $i -lt $block.Items.Count; $i++) {
        Add-Wrapped $block.Items[$i] "F1" 10.5 15 $Margin "$($i + 1). " 22 18
      }
      $Y -= 4
    }
  }
}

