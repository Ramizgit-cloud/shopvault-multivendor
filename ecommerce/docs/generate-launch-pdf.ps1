$Objects = New-Object System.Collections.ArrayList
function Add-Object([string]$Body) {
  [void]$script:Objects.Add($Body)
  return $script:Objects.Count
}

$CatalogId = Add-Object ""
$PagesId = Add-Object ""
$FontRegularId = Add-Object "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>"
$FontBoldId = Add-Object "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>"
$FontMonoId = Add-Object "<< /Type /Font /Subtype /Type1 /BaseFont /Courier >>"
$PageIds = New-Object System.Collections.ArrayList

foreach ($pageCommands in $Pages) {
  $stream = [string]::Join("`n", [string[]]$pageCommands)
  $streamLength = [Text.Encoding]::ASCII.GetByteCount($stream)
  $contentId = Add-Object "<< /Length $streamLength >>`nstream`n$stream`nendstream"
  $pageId = Add-Object "<< /Type /Page /Parent $PagesId 0 R /MediaBox [0 0 $PageWidth $PageHeight] /Resources << /Font << /F1 $FontRegularId 0 R /F2 $FontBoldId 0 R /F3 $FontMonoId 0 R >> >> /Contents $contentId 0 R >>"
  [void]$PageIds.Add($pageId)
}

$Objects[$CatalogId - 1] = "<< /Type /Catalog /Pages $PagesId 0 R >>"
$kidRefs = ($PageIds | ForEach-Object { "$_ 0 R" }) -join " "
$Objects[$PagesId - 1] = "<< /Type /Pages /Kids [$kidRefs] /Count $($PageIds.Count) >>"

$Pdf = "%PDF-1.4`n%PDFGEN`n"
$Offsets = New-Object System.Collections.ArrayList
[void]$Offsets.Add(0)
for ($i = 0; $i -lt $Objects.Count; $i++) {
  [void]$Offsets.Add([Text.Encoding]::ASCII.GetByteCount($Pdf))
  $Pdf += "$($i + 1) 0 obj`n$($Objects[$i])`nendobj`n"
}

$XrefOffset = [Text.Encoding]::ASCII.GetByteCount($Pdf)
$Pdf += "xref`n0 $($Objects.Count + 1)`n0000000000 65535 f `n"
for ($i = 1; $i -lt $Offsets.Count; $i++) {
  $Pdf += ("{0:D10} 00000 n `n" -f [int]$Offsets[$i])
}
$Pdf += "trailer`n<< /Size $($Objects.Count + 1) /Root $CatalogId 0 R >>`nstartxref`n$XrefOffset`n%%EOF`n"

[IO.File]::WriteAllBytes($OutputPath, [Text.Encoding]::ASCII.GetBytes($Pdf))
Write-Output "Generated $OutputPath"
